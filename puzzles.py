"""
puzzles.py -- permutation puzzles generated from geometry (no hard-coded tables).

A state is a permutation g of the sticker slots: g[i] = id of the sticker now
sitting in slot i (ids = home slot).  Applying a move m to a state is
    g  ->  g∘m        i.e. compose(g, m)
and a move *as a group element* is the state you get by applying it to the
solved state (the identity), so the puzzle group is G = <moves>.
"""
from __future__ import annotations

import itertools
import random

from permgroup import Perm, compose, identity, inverse

# face -> (axis index, sign).  x=R/L, y=U/D, z=F/B
FACES = {"U": (1, 1), "D": (1, -1), "R": (0, 1), "L": (0, -1), "F": (2, 1), "B": (2, -1)}


def _rot_cw(v, k):
    """Rotate v by -90 degrees about unit vector k (= clockwise seen from outside)."""
    d = k[0] * v[0] + k[1] * v[1] + k[2] * v[2]
    c = (k[1] * v[2] - k[2] * v[1], k[2] * v[0] - k[0] * v[2], k[0] * v[1] - k[1] * v[0])
    return tuple(k[i] * d - c[i] for i in range(3))


class Cube:
    """2x2x2 or 3x3x3 cube. Moves are generated by rotating sticker coordinates."""

    def __init__(self, n: int = 3, faces: str = "URFDLB"):
        assert n in (2, 3), "n must be 2 or 3"
        self.n = n
        coords = range(-(n - 1), n, 2)
        self.stickers: list[tuple[tuple, tuple]] = []     # (cubie position, normal)
        for pos in itertools.product(coords, repeat=3):
            if n == 3 and sum(1 for c in pos if c) == 1:  # face centers never move
                continue
            for a in range(3):
                if abs(pos[a]) == n - 1:
                    nrm = [0, 0, 0]
                    nrm[a] = 1 if pos[a] > 0 else -1
                    self.stickers.append((pos, tuple(nrm)))
        self.N = len(self.stickers)
        index = {s: i for i, s in enumerate(self.stickers)}

        self.moves: dict[str, Perm] = {}
        for f in faces:
            axis, sign = FACES[f]
            k = [0, 0, 0]
            k[axis] = sign
            m = list(range(self.N))
            for i, (pos, nrm) in enumerate(self.stickers):
                if pos[axis] * sign == n - 1:             # sticker is in the turning layer
                    j = index[(_rot_cw(pos, k), _rot_cw(nrm, k))]
                    m[j] = i                              # content of slot i moves to slot j
            m = tuple(m)
            self.moves[f] = m
            self.moves[f + "2"] = compose(m, m)
            self.moves[f + "'"] = inverse(m)
        self.id = identity(self.N)

    # ---- state helpers -------------------------------------------------
    def apply(self, state: Perm, seq) -> Perm:
        if isinstance(seq, str):
            seq = seq.split()
        for name in seq:
            state = compose(state, self.moves[name])
        return state

    def scramble(self, length: int = 25, rng: random.Random | None = None) -> tuple[Perm, list[str]]:
        rng = rng or random
        names = list(self.moves)
        seq, last = [], None
        while len(seq) < length:
            mv = rng.choice(names)
            if last and mv[0] == last[0]:
                continue
            seq.append(mv)
            last = mv
        return self.apply(self.id, seq), seq

    def gens(self, names) -> list[Perm]:
        return [self.moves[n] for n in names]

    # ---- sticker colorings (each defines a subgroup = "looks solved") ----
    def _kind(self, pos) -> int:
        return sum(1 for c in pos if c)                   # 3 = corner, 2 = edge

    def label_edge_orientation(self) -> list[int]:
        """Mark one sticker per edge. Stabilizer = <U,D,L,R,F2,B2> (F/B quarter turns flip edges)."""
        lab = []
        for pos, nrm in self.stickers:
            if self._kind(pos) == 2:
                ax = 1 if pos[1] != 0 else 2
                lab.append(1 if nrm[ax] != 0 else 0)
            else:
                lab.append(2)
        return lab

    def label_corner_orient_and_slice(self) -> list[int]:
        """Corner twist about the x-axis plus which 4 edges sit in the x=0 slice.
        Stabilizer (inside <U,D,L,R,F2,B2>) = <U2,D2,L,R,F2,B2>."""
        lab = []
        for pos, nrm in self.stickers:
            if self._kind(pos) == 3:
                lab.append(1 if nrm[0] != 0 else 0)
            else:
                lab.append(2 + (1 if pos[0] == 0 else 0))
        return lab

    def label_identity(self) -> list[int]:
        """Every sticker its own color: the stabilizer is the trivial group."""
        return list(range(self.N))
